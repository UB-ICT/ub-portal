import { mkdirSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { loadEnv } from "vite"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, "..")
const publicDir = path.join(rootDir, "public")
const outputPath = path.join(publicDir, "firebase-messaging-sw.js")
const mode = process.argv[2] || "localhost"
const env = loadEnv(mode, rootDir, "")

const config = {
  apiKey: env.VITE_FIREBASE_API_KEY ?? "",
  authDomain: env.VITE_FIREBASE_AUTH_DOMAIN ?? "",
  projectId: env.VITE_FIREBASE_PROJECT_ID ?? "",
  storageBucket: env.VITE_FIREBASE_STORAGE_BUCKET ?? "",
  messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID ?? "",
  appId: env.VITE_FIREBASE_APP_ID ?? "",
}

const contents = `/* Generated by scripts/generate-firebase-sw.mjs — do not edit manually. */
importScripts("https://www.gstatic.com/firebasejs/11.10.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/11.10.0/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(config, null, 2)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title || "New requisition notification";
  const body =
    payload.notification?.body ||
    payload.data?.message ||
    "A requisition reached your approval stage.";
  const requisitionId = payload.data?.requisition_id;
  const url =
    payload.data?.url ||
    (requisitionId ? "/requisitions/forms?requisition=" + requisitionId : "/");

  self.registration.showNotification(title, {
    body,
    icon: "/vite.svg",
    tag: payload.data?.type || "portal-notification",
    data: { url, requisition_id: requisitionId },
    silent: false,
  });
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();

  const targetUrl = event.notification.data?.url || "/";

  event.waitUntil(
    clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then((windowClients) => {
        for (const client of windowClients) {
          if ("focus" in client) {
            client.focus();
            if ("navigate" in client) {
              return client.navigate(targetUrl);
            }
          }
        }

        if (clients.openWindow) {
          return clients.openWindow(targetUrl);
        }

        return undefined;
      })
  );
});
`

mkdirSync(publicDir, { recursive: true })
writeFileSync(outputPath, contents, "utf8")

console.log(`Wrote ${outputPath}`)
